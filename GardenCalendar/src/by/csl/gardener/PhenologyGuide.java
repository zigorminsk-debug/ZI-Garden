    private PhenologyGuide() {
    }

    public static List<Sign> all() {
        return new ArrayList<>(ALL);
    }

    /** Признаки одного сезона в порядке справочника. */
    public static List<Sign> bySeason(String season) {
        List<Sign> out = new ArrayList<>();
        for (Sign s : ALL) {
            if (s.season.equals(season)) {
                out.add(s);
            }
        }
        return out;
    }

    /** Сезон по номеру месяца (1–12): 3–5 весна, 6–8 лето, 9–11 осень, 12–2 зима. */
    public static String seasonFor(int month) {
        if (month >= 3 && month <= 5) {
            return "Весна";
        }
        if (month >= 6 && month <= 8) {
            return "Лето";
        }
        if (month >= 9 && month <= 11) {
            return "Осень";
        }
        return "Зима";
    }

    /** Эмодзи сезона (для карточек «Сейчас в природе»). */
